      }
    ],
    "rewrites": [
      {
        "source": "/b/**",
        "destination": "/b/admin.html"
      }
    ]
  }
}
'@
  [IO.File]::WriteAllText($fj, $json.Trim() + "`n", $utf8)
  Write-Host "Criei firebase.json para publicar esta pasta."
}
