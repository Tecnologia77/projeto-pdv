function Add-AdminButton([string]$html) {
  $url = "https://linkagendamentoonline.web.app/"
  if ($html -notmatch 'id="btnOpenAdmin"' -and $html -match 'app-switch-link">Sou barbeiro') {
    $html = [regex]::Replace($html, 'href="[^"]*"(\s+class="salon-btn-ghost app-switch-link">Sou barbeiro)', "id=`"btnOpenAdmin`" href=`"$url`"`$1", 1)
  }
  if ($html -notmatch 'id="btnOpenAdmin"' -and $html -match 'salon-content public-page') {
    $button = '<a id="btnOpenAdmin" href="' + $url + '" style="position:sticky;top:0;z-index:40;display:flex;align-items:center;justify-content:center;margin:0 0 0.75rem;padding:0.85rem 1rem;border-radius:999px;background:#1a1d24;color:#fff;text-decoration:none;font-weight:700;text-align:center;">Sou barbeiro - abrir painel admin</a>'
    $html = [regex]::Replace($html, '(<div class="salon-content public-page">)', ('$1' + $button), 1)
  }
  if ($html -match 'id="btnOpenAdmin"' -and $html -notmatch 'id="btnOpenAdmin-boot"') {
    $script = '<script id="btnOpenAdmin-boot">(function(){var link=document.getElementById("btnOpenAdmin");if(!link)return;link.addEventListener("click",function(ev){ev.preventDefault();window.location.href="https://linkagendamentoonline.web.app/";});})();</script>'
    $html = $html.Replace("</body>", $script + "</body>")
  }
  return $html
}


function Add-SubscriberScript([string]$html) {
  $isClient = ($html -match 'id="historyPanel"') -or ($html -match 'id="clientPanel"')
  $isBarber = ($html -match 'id="barberApp"') -or ($html -match 'SALAO_PAGE = "barbeiro"')
  if (-not $isClient -and -not $isBarber) { return $html }
  if ($html -match 'cliente-assinatura\.js') {
    return [regex]::Replace($html, 'cliente-assinatura\.js(\?v=\d+)?', 'cliente-assinatura.js?v=2')
  }
  $tag = '<script src="/js/cliente-assinatura.js?v=2"></script>'
  return $html.Replace("</body>", ($tag + "</body>"))
}

function Ensure-BookingPage {
  $bDir = Join-Path $site "b"
  $booking = Join-Path $bDir "admin.html"
  if (Test-Path $booking) { return $true }
  if (-not (Test-Path $bDir)) { New-Item -ItemType Directory -Force -Path $bDir | Out-Null }
  $found = @()
  Get-ChildItem -Path $site -Filter *.html -Recurse -File -ErrorAction SilentlyContinue |
    Where-Object { $_.FullName -notmatch '\\node_modules\\' } |
    ForEach-Object {
      $text = [IO.File]::ReadAllText($_.FullName)
      if ($text -match 'id="historyPanel"' -or $text -match 'salon-content public-page' -or $text -match 'SALAO_PAGE = "public"') {
        $found += $_.FullName
      }
    }
  $picked = $null
  foreach ($item in $found) {
    if ($item -match '\\b\\') { $picked = $item; break }
  }
  if (-not $picked -and $found.Count -gt 0) { $picked = $found[0] }
  if ($picked) {
    Copy-Item $picked $booking -Force
    Write-Host "Copiei a pagina de agendamento para b\admin.html."
    return $true
  }
  try { [Net.ServicePointManager]::SecurityProtocol = [Net.SecurityProtocolType]::Tls12 } catch {}
  $prevProgress = $ProgressPreference
  $ProgressPreference = "SilentlyContinue"
  $urls = @(
    "https://linkagendamentoonline.web.app/b/admin.html",
    "https://linkagendamentoonline.web.app/b/demo"
  )
  foreach ($url in $urls) {
    try {
      Invoke-WebRequest -Uri $url -OutFile $booking -UseBasicParsing
      $saved = [IO.File]::ReadAllText($booking)
      if ($saved.Length -gt 1000 -and ($saved -match 'historyPanel' -or $saved -match 'public-page')) {
        $ProgressPreference = $prevProgress
        Write-Host "Recuperei a pagina de agendamento que ja esta no ar para b\admin.html."
        return $true
      }
    } catch {}
  }
  $ProgressPreference = $prevProgress
  if (Test-Path $booking) { Remove-Item $booking -Force }
  return $false
}

